// Local Chrome checks of acknowledgment, separate sharing choices and responsive layout.
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { ACKNOWLEDGMENT_KEY, NOTICE_VERSION } from '../src/privacy/acknowledgment.js';

const output = new URL('../../artifacts/privacy/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const records = [], errors = [];
try {
  for (const [lang, width, height] of [['en', 1440, 1000], ['en', 390, 844], ['tl', 390, 844], ['taglish', 390, 844], ['en', 320, 568], ['en', 844, 390]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' });
    const uploads = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.method() === 'POST') uploads.push(request.url()); });
    await page.addInitScript(({ lang, key }) => {
      localStorage.setItem('surfare-welcome-seen', 'true');
      localStorage.setItem('surfare-language', lang);
      localStorage.setItem(key, JSON.stringify({ version: '2026-11-25.1', acceptedAt: new Date().toISOString() }));
    }, { lang, key: ACKNOWLEDGMENT_KEY });
    await page.goto(process.env.SURFARE_BASE_URL || 'http://localhost:5173', { waitUntil: 'domcontentloaded' });
    const dialog = page.locator('.privacy-notice');
    await dialog.waitFor();
    await page.evaluate(() => document.fonts.ready);
    const checks = dialog.locator('input[type="checkbox"]');
    assert.equal(await checks.count(), 1);
    assert.equal(await dialog.locator('input:checked').count(), 0);
    assert.equal(await checks.isDisabled(), true);
    assert.equal(await dialog.locator('.notice-accept').isDisabled(), true);
    await dialog.locator('form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })));
    assert.equal(await dialog.isVisible(), true);
    const layout = await dialog.evaluate(element => {
      const bounds = element.getBoundingClientRect();
      const footer = element.querySelector('.notice-actions').getBoundingClientRect();
      return { insideViewport: bounds.top >= 0 && bounds.bottom <= innerHeight + 1 && bounds.left >= 0 && bounds.right <= innerWidth + 1,
        noHorizontalOverflow: element.scrollWidth <= element.clientWidth + 1,
        footerVisible: footer.top >= bounds.top && footer.bottom <= bounds.bottom + 1 };
    });
    assert.deepEqual(layout, { insideViewport: true, noHorizontalOverflow: true, footerVisible: true });
    assert.equal(await dialog.locator('.notice-illustration, .notice-select-all, .notice-brand-panel').count(), 0);
    assert.match(await dialog.innerText(), /Sightengine/);
    assert.match(await dialog.innerText(), /OpenRouter/);
    await dialog.screenshot({ path: fileURLToPath(new URL(`${lang}-${width}x${height}.png`, output)) });
    const scroller = dialog.locator('.notice-scroll');
    await scroller.evaluate(element => { element.scrollTop = (element.scrollHeight - element.clientHeight) / 2; });
    await page.waitForFunction(() => document.querySelector('.notice-reading-track > span').style.transform !== 'scaleX(0)');
    assert.equal(await checks.isDisabled(), true, 'reading halfway must not unlock acknowledgment');
    assert.equal(await dialog.locator('.notice-accept').isDisabled(), true);
    await scroller.focus();
    if (width === 1440) {
      const bounds = await scroller.boundingBox();
      await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
      await page.mouse.wheel(0, 5000);
    } else await page.keyboard.press('End');
    await page.waitForFunction(() => !document.querySelector('.notice-final-ack input').disabled);
    assert.equal(await checks.isChecked(), false, 'reaching the end must not automatically select consent');
    assert.equal(await dialog.locator('.notice-accept').isDisabled(), true);
    await checks.check();
    assert.equal(await dialog.locator('.notice-accept').isEnabled(), true);
    await checks.uncheck();
    assert.equal(await dialog.locator('.notice-accept').isDisabled(), true);
    await checks.check();
    await dialog.locator('.notice-close').focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await dialog.locator('.notice-accept').evaluate(element => element === document.activeElement), true);
    assert((await dialog.locator('.notice-policy-body > section').count()) >= 7);
    assert.match(await dialog.locator('.notice-policy-body').innerText(), /OpenRouter/);
    assert.equal(await dialog.locator('.notice-actions').isVisible(), true);
    if (width === 1440) await dialog.screenshot({ path: fileURLToPath(new URL('desktop-ready.png', output)) });
    await dialog.locator('.notice-accept').click();
    await dialog.waitFor({ state: 'detached' });
    const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), ACKNOWLEDGMENT_KEY);
    assert.equal(saved.version, NOTICE_VERSION);
    assert.deepEqual(Object.keys(saved).sort(), ['acceptedAt', 'version']);
    assert.notEqual(await page.evaluate(() => sessionStorage.getItem('surfare-ai-opt-in')), 'true');
    assert.deepEqual(uploads, []);
    const infoButton = page.locator('.check-ai-details');
    await infoButton.click();
    const help = page.locator('.check-ai-explainer');
    await help.waitFor();
    assert.equal(await page.locator('.privacy-notice').count(), 0);
    assert.equal(await infoButton.getAttribute('aria-expanded'), 'true');
    assert.match(await help.innerText(), /Surfy/);
    assert.equal(await page.locator('.check-ai-choice input').isChecked(), true);
    const helpFits = await help.evaluate(element => {
      const bounds = element.getBoundingClientRect();
      return bounds.left >= 0 && bounds.right <= innerWidth + 1 && element.scrollWidth <= element.clientWidth + 1;
    });
    assert(helpFits);
    await help.screenshot({ path: fileURLToPath(new URL(`ai-info-${lang}-${width}.png`, output)) });
    await help.locator('.check-ai-explainer-close').focus();
    await page.keyboard.press('Escape');
    await help.waitFor({ state: 'detached' });
    assert.equal(await infoButton.evaluate(element => element === document.activeElement), true);
    await page.locator('.footer-privacy-link').click();
    await dialog.waitFor();
    assert.equal(await dialog.locator('input[type="checkbox"]').isDisabled(), true, 'review starts with a fresh scroll gate');
    assert.equal(await dialog.locator('input[type="checkbox"]').isChecked(), false);
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'detached' });
    assert.equal(await page.locator('.footer-privacy-link').evaluate(element => element === document.activeElement), true);
    records.push({ lang, width, height, ...layout, acknowledgments: 1, scrollGate: true, defaultAiDoesNotSubmit: true, keyboardTrapAndDismiss: true });
    await page.close();
  }
  // Declining must not create an acknowledgment or enable AI sharing.
  const page = await browser.newPage({ reducedMotion: 'reduce' });
  await page.addInitScript(() => {
    localStorage.setItem('surfare-welcome-seen', 'true');
    sessionStorage.setItem('surfare-ai-opt-in', 'false');
  });
  await page.goto(process.env.SURFARE_BASE_URL || 'http://localhost:5173', { waitUntil: 'domcontentloaded' });
  await page.locator('.privacy-notice .notice-decline').click();
  await page.locator('.privacy-notice').waitFor({ state: 'detached' });
  assert.equal(await page.evaluate(key => localStorage.getItem(key), ACKNOWLEDGMENT_KEY), null);
  assert.notEqual(await page.evaluate(() => sessionStorage.getItem('surfare-ai-opt-in')), 'true');
  // The compact toggle must still require the notice; its info button must not toggle AI.
  const control = page.locator('.check-ai-control');
  const aiToggle = control.locator('input');
  const requests = [];
  page.on('request', request => { if (request.method() === 'POST') requests.push(request.url()); });
  assert.equal(await control.locator('small').count(), 0);
  assert.equal(await aiToggle.isChecked(), false);
  await aiToggle.click();
  await page.locator('.privacy-notice').waitFor();
  await page.locator('.privacy-notice .notice-decline').click();
  await page.locator('.privacy-notice').waitFor({ state: 'detached' });
  assert.equal(await aiToggle.isChecked(), false);
  await aiToggle.click();
  await page.locator('.privacy-notice .notice-scroll').focus();
  await page.keyboard.press('End');
  await page.waitForFunction(() => !document.querySelector('.notice-final-ack input').disabled);
  await page.locator('.notice-final-ack input').check();
  await page.locator('.privacy-notice .notice-accept').click();
  await page.locator('.privacy-notice').waitFor({ state: 'detached' });
  assert.equal(await aiToggle.isChecked(), true);
  await control.locator('.check-ai-details').click();
  const explainer = page.locator('.check-ai-explainer');
  await explainer.waitFor();
  assert.equal(await page.locator('.privacy-notice').count(), 0, 'info opens a small explanation instead of the full notice');
  assert.match(await explainer.innerText(), /Surfy/);
  assert.match(await explainer.innerText(), /online AI services/);
  assert.match(await explainer.innerText(), /does not save a check history/);
  assert.equal(await aiToggle.isChecked(), true);
  await page.locator('.check-form-column').screenshot({ path: fileURLToPath(new URL('ai-help-info.png', output)) });
  await explainer.locator('.check-ai-policy-link').click();
  await page.locator('.privacy-notice').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.privacy-notice').waitFor({ state: 'detached' });
  assert.equal(await aiToggle.isChecked(), true);
  await explainer.locator('.check-ai-explainer-close').click();
  await explainer.waitFor({ state: 'detached' });
  assert.equal(await control.locator('.check-ai-details').evaluate(element => document.activeElement === element), true);
  await control.locator('.check-ai-details').click();
  await page.keyboard.press('Escape');
  await explainer.waitFor({ state: 'detached' });
  await aiToggle.uncheck();
  assert.equal(await aiToggle.isChecked(), false);
  assert.deepEqual(requests, []);
  await control.screenshot({ path: fileURLToPath(new URL('compact-online-control.png', output)) });
  await page.close();
  assert.deepEqual(errors, []);
  await writeFile(new URL('smoke.json', output), JSON.stringify({ records, decliningDoesNotSave: true, errors }, null, 2) + '\n');
  console.log(JSON.stringify({ layouts: records.length, acknowledgments: 1, scrollGate: true, separateAiConsent: true, declineAndEscape: true, errors }, null, 2));
} finally { await browser.close(); }
