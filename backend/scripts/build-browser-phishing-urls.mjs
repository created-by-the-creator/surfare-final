// Complete source-corpus coverage, independent of any evaluation case selection.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {parseCsvRows} from '../lib/csv-rows.js';
const root=path.resolve(import.meta.dirname,'../..');
const source=path.join(root,'backend/datasets/PhiUSIIL_Phishing_URL_Dataset.csv');
const bytes=fs.readFileSync(source);const records=parseCsvRows(bytes.toString('utf8'));
const headers=records.next().value.map(v=>v.trim().toLowerCase());
const urlColumn=headers.indexOf('url'),labelColumn=headers.indexOf('label');
if(urlColumn<0||labelColumn<0)throw Error('Missing source columns');
const labels=new Map();let invalid=0,conflicting=0;
for(const row of records){
 try{
  const url=new URL(row[urlColumn]);const label=String(row[labelColumn]).trim();
  if(!['http:','https:'].includes(url.protocol)||!['0','1'].includes(label)){invalid++;continue;}
  const known=labels.get(url.href);
  if(known===undefined)labels.set(url.href,label);
  else if(known!==label&&known!=='conflict'){labels.set(url.href,'conflict');conflicting++;}
 }catch{invalid++;}
}
const fingerprints=[...new Set([...labels].filter(([,label])=>label==='0').map(([url])=>createHash('sha256').update(url).digest('hex').slice(0,16)))].sort();
const payload=Buffer.from(fingerprints.join(''),'hex');
const encoded=payload.toString('base64');const chunks=encoded.match(/.{1,1024}/g)||[];
const metadata={source:'PhiUSIIL URL dataset; 0 = phishing, 1 = legitimate',sourceSha256:createHash('sha256').update(bytes).digest('hex'),count:fingerprints.length,fingerprintBytes:8,invalidRows:invalid,conflictingUrls:conflicting,scope:'Exact normalized URL fingerprints only. No domain-wide blocking or safe-list. Not a live reputation service.'};
const output=path.join(root,'frontend/src/engine/generated/phishing-url-data.js');
fs.writeFileSync(output,'// GENERATED by backend/scripts/build-browser-phishing-urls.mjs. Do not edit.\n'+
 'export const PHISHING_URL_INDEX = Object.freeze('+JSON.stringify(metadata,null,2)+');\n'+
 'export const PHISHING_URL_BYTES_BASE64 = [\n'+chunks.map(c=>'  '+JSON.stringify(c)+',').join('\n')+'\n].join(\'\');\n');
console.log(JSON.stringify({...metadata,encodedBytes:encoded.length,output},null,2));
